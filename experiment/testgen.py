import numpy as np
import jax
from pathlib import Path

def c_array(name, arr):
    typestr = ""
    width = 0
    if arr.dtype == np.float16:
        bits = np.asarray(arr, dtype=np.float16).reshape(-1).view(np.uint16)
        typestr = "uint16_t"
        width = 4
    elif arr.dtype == np.float32:
        bits = np.asarray(arr, dtype=np.float32).reshape(-1).view(np.uint32)
        typestr = "uint32_t"
        width = 8
    else:
        raise ValueError(f"ERROR: Unsupported data type {arr.dtype}!")

    body = ",\n  ".join(
        ", ".join(f"0x{v:0{width}x}" for v in bits[i:i + 8])
        for i in range(0, bits.size, 8)
    )
    return f"{typestr} {name}[{bits.size}] = {{\n  {body}\n}};\n"

def export_mlir(function, args, out_path):
    stablehlo_out = (jax.export.export(function)(*args).mlir_module())
    with open(out_path, "w") as file:
        file.write(stablehlo_out)

def write_data(test_name: str, inputs, expected_outputs, out_path):
    Path(out_path).parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w") as f:
        f.write("// Generated by testgen.py do not edit.\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        for name, arr in inputs.items():
            f.write(f"#define {name}_LEN {arr.size}\n")
            f.write(c_array(name, arr) + "\n")
        for name, arr in expected_outputs.items():
            f.write(f"#define {name}_expected_LEN {arr.size}\n")
            f.write(c_array(f"{name}_expected", arr) + "\n")

