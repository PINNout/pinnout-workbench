import numpy as np
import jax
from pathlib import Path

def dtype_tag(value):
    if value.dtype == np.float16:
        return "DT_F16"
    elif value.dtype == np.float32:
        return "DT_F32"
    else:
        raise ValueError(f"ERROR: Unspported data type {value.dtype}!")


def c_array(name, arr, write_body=True):
    typestr = ""
    width = 0
    if arr.dtype == np.float16:
        bits = np.asarray(arr, dtype=np.float16).reshape(-1).view(np.uint16)
        typestr = "uint16_t"
        width = 4
    elif arr.dtype == np.float32:
        bits = np.asarray(arr, dtype=np.float32).reshape(-1).view(np.uint32)
        typestr = "uint32_t"
        width = 8
    else:
        raise ValueError(f"ERROR: Unsupported data type {arr.dtype}!")

    if write_body:
        body = ",\n  ".join(
            ", ".join(f"0x{v:0{width}x}" for v in bits[i:i + 8])
            for i in range(0, bits.size, 8)
        )
        return f"{typestr} {name}[{bits.size}] = {{\n  {body}\n}};\n"
    else:
        return f"{typestr} {name}[{bits.size}];\n"

def export_mlir(function, args, out_path):
    stablehlo_out = (jax.export.export(function)(*args).mlir_module())
    with open(out_path, "w") as file:
        file.write(stablehlo_out)

def write_data(test_name: str, inputs, outputs, out_path):
    Path(out_path).parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w") as f:
        f.write("// Generated by testgen.py do not edit.\n")
        f.write(f'#pragma once\n#include <stdint.h>\n#include "compare.h"\n#include "{test_name}.h"\n\n')

        f.write(f"#define NUM_OUTPUTS {len(outputs)}\n\n")
        for name, arr in inputs.items():
            f.write(f"#define {name}_LEN {arr.size}\n")
            f.write(c_array(name, arr) + "\n")
        for name, arr in outputs.items():
            f.write(f"#define {name}_expected_LEN {arr.size}\n")
            f.write(c_array(name, arr, False) + "\n")
            f.write(c_array(f"{name}_expected", arr) + "\n")

        params = [f"{{ (void *){name}, (void *){name}_expected, {name}_expected_LEN, {dtype_tag(arr)} }}" for name, arr in outputs.items()]
        f.write(f"static const output_t outputs[NUM_OUTPUTS] = {{\n  {',\n '.join(params)} \n}};\n\n")

        args = [f"(void *){name}" for name in list(inputs) + list(outputs)]
        f.write(f"static void run_kernel(void) {{ {test_name}({', '.join(args)}); }}\n")
        


