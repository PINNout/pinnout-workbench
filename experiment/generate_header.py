# Test data for the matmul experiment.
#
# Writes A, B and the expected C = A @ B (all N x N, fp16) to a C header,
# as raw 16-bit patterns in uint16_t arrays. The test casts them to
# _Float16[N][N] when calling the generated matmul().
#
# Values are drawn from [-1, 1], so every partial sum stays small and well
# inside the fp16 range.

import argparse
import os

import jax
import jax.numpy as jnp
import numpy as np


def c_array(name, arr):
    # .view(np.uint16) reinterprets the fp16 bytes; no value conversion.
    bits = np.asarray(arr, dtype=np.float16).reshape(-1).view(np.uint16)
    body = ",\n  ".join(
        ", ".join(f"0x{v:04x}" for v in bits[i:i + 8])
        for i in range(0, bits.size, 8)
    )
    return f"uint16_t {name}[{bits.size}] = {{\n  {body}\n}};\n"


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    p = argparse.ArgumentParser(description="fp16 matmul test data generator")
    p.add_argument("--n", type=int, default=16, help="matrix size (N x N)")
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--out", default=os.path.join(here, "matmul/include/matmul_data.h"))
    args = p.parse_args()

    ka, kb = jax.random.split(jax.random.key(args.seed))
    A = jax.random.uniform(ka, (args.n, args.n), minval=-1.0, maxval=1.0).astype(jnp.float16)
    B = jax.random.uniform(kb, (args.n, args.n), minval=-1.0, maxval=1.0).astype(jnp.float16)
    C = jnp.matmul(A, B)  # fp16 result; JAX may accumulate in fp32 internally

    # fp32 reference of the same fp16 inputs, only to report the gap.
    C32 = np.asarray(A, np.float32) @ np.asarray(B, np.float32)
    gap = np.max(np.abs(np.asarray(C, np.float32) - C32))

    with open(args.out, "w") as f:
        f.write("// Generated by gen_matmul_data.py, do not edit.\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write(f"#define MATMUL_N {args.n}\n\n")
        f.write(c_array("A", A) + "\n")
        f.write(c_array("B", B) + "\n")
        f.write(c_array("C_expected", C))

    print(f"wrote {args.out} (N={args.n}, seed={args.seed})")
    print(f"max |JAX fp16 result - fp32 reference| = {gap:.3e}")


if __name__ == "__main__":
    main()
